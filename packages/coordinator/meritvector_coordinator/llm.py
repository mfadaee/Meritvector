"""Optional LLM provider interface.

MeritVector does not depend on an LLM. v0.1 ships only a deterministic provider that
produces rule-based text and labels it as such. A real provider can be registered
later (see ROADMAP.md, v0.3) by implementing :class:`LLMProvider`; until then any
configured provider name other than ``deterministic`` falls back with a warning and
the output says so. Mock output is never presented as an LLM result.
"""

from __future__ import annotations

import logging
import os
from dataclasses import dataclass
from typing import Protocol

log = logging.getLogger(__name__)


@dataclass(frozen=True)
class GenerationResult:
    text: str
    provider: str
    is_llm: bool
    disclosure: str


class LLMProvider(Protocol):
    name: str

    def generate(self, prompt: str, *, purpose: str, fallback_text: str) -> GenerationResult: ...


class DeterministicProvider:
    """Returns the rule-based text computed by the coordinator, clearly labelled."""

    name = "deterministic"

    def generate(self, prompt: str, *, purpose: str, fallback_text: str) -> GenerationResult:
        return GenerationResult(
            text=fallback_text,
            provider=self.name,
            is_llm=False,
            disclosure="Generated by deterministic rules (no language model was used).",
        )


_REGISTRY: dict[str, LLMProvider] = {"deterministic": DeterministicProvider()}


def register_provider(provider: LLMProvider) -> None:
    _REGISTRY[provider.name] = provider


def get_provider(name: str | None = None) -> LLMProvider:
    wanted = (name or os.getenv("MV_LLM_PROVIDER") or "deterministic").strip().lower()
    if wanted not in _REGISTRY:
        log.warning("LLM provider %r is not available in this build; using deterministic rules.", wanted)
        return _REGISTRY["deterministic"]
    return _REGISTRY[wanted]
