"""Build research/references/library.json — the research evidence library.

Single source of truth for docs/research/LITERATURE_REVIEW.md and the Research
Laboratory's evidence library. Each entry was checked during the 2026-10-13 research
session using web search against bibliographic records (publisher pages, PubMed,
RePEc, institutional repositories). `verification` records what was confirmed:

* "doi_confirmed"       — bibliographic details and DOI confirmed by >= 1 independent record
* "citation_confirmed"  — authors/year/title/venue confirmed; DOI not confirmed (stable URL given)
* "official_source"     — standard, statute or framework located on the issuing body's site

No entry was added from memory without a check. Findings are paraphrased summaries;
`evidence_type` distinguishes empirical findings from conceptual frameworks.
"""

from __future__ import annotations

import json
from pathlib import Path

E = []


def add(
    id,
    authors,
    year,
    title,
    venue,
    *,
    doi=None,
    url=None,
    verification,
    area,
    evidence_type,
    finding,
    limitations,
    relevance,
    implications,
):
    E.append(
        {
            "id": id,
            "authors": authors,
            "year": year,
            "title": title,
            "venue": venue,
            "doi": doi,
            "url": url or (f"https://doi.org/{doi}" if doi else None),
            "verification": verification,
            "area": area,
            "evidence_type": evidence_type,
            "main_finding": finding,
            "limitations": limitations,
            "relevance": relevance,
            "design_implications": implications,
        }
    )


